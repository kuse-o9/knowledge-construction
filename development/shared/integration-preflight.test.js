'use strict';
const assert=require('node:assert/strict');
const signals=require('./rail-signals.js'),through=require('./through-services.js'),portal=require('./tunnel-portals.js');
const blocks=signals.buildBlocks(600,[200,400]);
const route={id:'R1',trackId:'track-A',resources:['switch-1','block-A'],switchAligned:true};
assert.equal(signals.signalForRoute(blocks,1,[{id:'T1',trackId:'track-A',front:270,length:30}],route),'RED');
assert.equal(signals.signalForRoute(blocks,1,[{id:'T2',trackId:'track-B',front:270,length:30}],route),'GREEN');
assert.equal(signals.routeClear(route,[{id:'OTHER',resources:['switch-1'],active:true}]),false);
assert.equal(signals.routeClear({...route,switchAligned:false},[]),false);
const from={operator:'A',id:'a',endStation:'X',endNode:'x',gaugeMm:1067,power:'DC',control:'ATS'};
const to={operator:'B',id:'b',startStation:'X',startNode:'x',gaugeMm:1067,power:'DC',control:'ATS',maxCars:10};
const service={allowedOperators:['A','B'],allowedPaths:['a>b']};
const train={gaugeMm:1067,supportedPower:['DC'],supportedControl:['ATS'],cars:8};
assert.equal(through.validate(from,to,service,train).ok,true);
assert.equal(through.validate(from,{...to,startNode:'other'},service,train).ok,false);
const shape=portal.portal({trackCenter:[0,0],heading:0,width:12,height:8,depth:25,groundY:10,railY:3});
assert.equal(shape.cutout.polygon.length,4);
assert.equal(shape.needsTerrainBoolean,true);
console.log('BAYLINE integration preflight: 8 checks passed. Browser/GPU not tested.');
